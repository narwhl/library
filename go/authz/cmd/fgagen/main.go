// Command fgagen generates Go constants for the object types and relations
// declared in an OpenFGA authorization model DSL file.
//
// Add it to an application's go.mod as a tool:
//
//	go get -tool pkg.narwhl.dev/authz/cmd/fgagen
//
// and run it from a go:generate directive in the package that holds the
// model:
//
//	//go:generate go tool fgagen
//
// By default it reads model.openfga and writes types.gen.go in the current
// directory, and names the output package after $GOPACKAGE, which go generate
// sets. The -model, -out, and -package flags override each default.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/openfga/language/pkg/go/transformer"
)

type typeDef struct {
	Name      string
	CamelName string
	Relations []relationDef
}

type relationDef struct {
	Name      string
	CamelName string
}

func toCamel(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "fgagen:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	fs := flag.NewFlagSet("fgagen", flag.ContinueOnError)
	modelPath := fs.String("model", "model.openfga", "path of the OpenFGA model DSL file")
	outPath := fs.String("out", "types.gen.go", "path of the generated Go file")
	pkg := fs.String("package", os.Getenv("GOPACKAGE"), "package name of the generated file (default $GOPACKAGE)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *pkg == "" {
		return errors.New("no package name: pass -package or run from a go:generate directive, which sets $GOPACKAGE")
	}

	// A missing model fails here, so a directive run from the wrong directory
	// cannot pass as a successful no-op.
	dsl, err := os.ReadFile(*modelPath)
	if err != nil {
		cwd, _ := os.Getwd()
		return fmt.Errorf("read %s in %s: %w; run go generate in the package that holds the model, or pass -model", *modelPath, cwd, err)
	}

	src, n, err := generate(string(dsl), *pkg, filepath.Base(*modelPath))
	if err != nil {
		return err
	}
	if err := os.WriteFile(*outPath, src, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", *outPath, err)
	}
	fmt.Printf("fgagen: wrote %s (%d types)\n", *outPath, n)
	return nil
}

// generate returns the formatted Go source for the model in dsl and the
// number of object types it declares. source names the model file in the
// generated header.
func generate(dsl, pkg, source string) ([]byte, int, error) {
	model, err := transformer.TransformDSLToProto(dsl)
	if err != nil {
		return nil, 0, fmt.Errorf("parse DSL: %w", err)
	}

	types := make([]typeDef, 0, len(model.GetTypeDefinitions()))
	for _, td := range model.GetTypeDefinitions() {
		t := typeDef{Name: td.GetType(), CamelName: toCamel(td.GetType())}
		relNames := make([]string, 0, len(td.GetRelations()))
		for name := range td.GetRelations() {
			relNames = append(relNames, name)
		}
		sort.Strings(relNames)
		for _, n := range relNames {
			t.Relations = append(t.Relations, relationDef{Name: n, CamelName: toCamel(n)})
		}
		types = append(types, t)
	}
	sort.Slice(types, func(i, j int) bool { return types[i].Name < types[j].Name })

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by fgagen. DO NOT EDIT.\n// Source: %s\n\npackage %s\n", source, pkg)

	fmt.Fprintf(&buf, "\n// Object types correspond to the `type` declarations in %s.\n", source)
	buf.WriteString("const (\n")
	for _, t := range types {
		fmt.Fprintf(&buf, "\tObjectType%s = %q\n", t.CamelName, t.Name)
	}
	buf.WriteString(")\n")

	for _, t := range types {
		if len(t.Relations) == 0 {
			continue
		}
		fmt.Fprintf(&buf, "\n// Relations on the %s type.\n", t.Name)
		buf.WriteString("const (\n")
		for _, r := range t.Relations {
			fmt.Fprintf(&buf, "\tRelation%s%s = %q\n", t.CamelName, r.CamelName, r.Name)
		}
		buf.WriteString(")\n")
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, 0, fmt.Errorf("gofmt: %w\n---\n%s", err, buf.String())
	}
	return formatted, len(types), nil
}

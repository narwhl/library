package main

import (
	"os"
	"path/filepath"
	"testing"
)

const testModel = `model
  schema 1.1

type user

type course_group
  relations
    define member: [user]
    define can_view: member
`

const wantSource = `// Code generated by fgagen. DO NOT EDIT.
// Source: model.openfga

package authz

// Object types correspond to the ` + "`type`" + ` declarations in model.openfga.
const (
	ObjectTypeCourseGroup = "course_group"
	ObjectTypeUser        = "user"
)

// Relations on the course_group type.
const (
	RelationCourseGroupCanView = "can_view"
	RelationCourseGroupMember  = "member"
)
`

func TestGenerate(t *testing.T) {
	got, n, err := generate(testModel, "authz", "model.openfga")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if n != 2 {
		t.Errorf("type count = %d, want 2", n)
	}
	if string(got) != wantSource {
		t.Errorf("generated source mismatch\n--- got ---\n%s\n--- want ---\n%s", got, wantSource)
	}
}

func TestGenerate_InvalidDSL(t *testing.T) {
	if _, _, err := generate("not a model", "authz", "model.openfga"); err == nil {
		t.Fatal("generate accepted an invalid model")
	}
}

func TestRun_PackageFromEnvironment(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	t.Setenv("GOPACKAGE", "acl")
	if err := os.WriteFile("model.openfga", []byte(testModel), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := run(nil); err != nil {
		t.Fatalf("run: %v", err)
	}
	src, err := os.ReadFile(filepath.Join(dir, "types.gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	want, _, _ := generate(testModel, "acl", "model.openfga")
	if string(src) != string(want) {
		t.Errorf("written file does not match generate output for package acl")
	}
}

func TestRun_NoPackage(t *testing.T) {
	t.Chdir(t.TempDir())
	t.Setenv("GOPACKAGE", "")
	if err := run(nil); err == nil {
		t.Fatal("run succeeded without a package name")
	}
}

func TestRun_MissingModel(t *testing.T) {
	t.Chdir(t.TempDir())
	t.Setenv("GOPACKAGE", "authz")
	if err := run(nil); err == nil {
		t.Fatal("run succeeded without a model file")
	}
}
